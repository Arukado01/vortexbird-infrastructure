    [string]$FrontendUrl,
    [ValidatePattern('^[A-Fa-f0-9]{8}-(?:[A-Fa-f0-9]{4}-){3}[A-Fa-f0-9]{12}$')][string]$RailwayProjectId,
    [ValidateNotNullOrEmpty()][string]$RailwayCli = 'railway',
    [ValidateNotNullOrEmpty()][string]$RailwayEnvironment = 'production',
    [switch]$Apply,
    [switch]$IncludeBindingManifest
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$region = 'us-east-2'
$account = '946876341107'
$poolId = 'us-east-2_nLop817zD'
$clientId = '3leshk5524vr3rrc82g1trijub'
$clientName = 'vortexbird-portal'
$domainPrefix = 'vortexbird-pilot-946876341107-ohio'
$existingPortal = 'https://vortexbird.pgecolombia.com/'
$scope = 'vortexbird-api/access'
$roles = @(
    'SUPER_ADMIN', 'ADMIN', 'ARCHITECT', 'INTEGRATION_MANAGER', 'OPERATIONS',
    'SECURITY_AUDITOR', 'PARTNER_ADMIN', 'PARTNER_USER', 'VIEWER'
)
$issuer = "https://cognito-idp.$region.amazonaws.com/$poolId"
$authorizationOrigin = "https://$domainPrefix.auth.$region.amazoncognito.com"
$aws = (Get-Command aws -CommandType Application -ErrorAction Stop).Source
$awsOptions = @('--profile', $Profile, '--region', $region, '--output', 'json',
    '--no-cli-pager', '--cli-connect-timeout', '8', '--cli-read-timeout', '20')

function Invoke-AwsJson {
    param([string[]]$Arguments, [string]$Resource)

    $previousErrorPreference = $ErrorActionPreference
    try {
        $ErrorActionPreference = 'Continue'
        $output = & $aws @Arguments @awsOptions 2>&1
        $exitCode = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $previousErrorPreference
    }
    $raw = ($output | ForEach-Object { $_.ToString() }) -join [Environment]::NewLine
    if ($exitCode -ne 0) {
        $detail = "AWS CLI exit code $exitCode"
        if ($raw -match '\((?<code>[A-Za-z][A-Za-z0-9]+)\) when calling') {
            $detail = $Matches.code
        } elseif ($raw -match 'Could not connect to the endpoint URL: "(?<endpoint>https://[a-z0-9.-]+/?)"') {
            $detail = "Could not connect to the endpoint URL: $($Matches.endpoint)"
        }
        throw "AWS $($Arguments[0]) $($Arguments[1]) failed for ${Resource}: $detail."
    }
    try {
        return ConvertFrom-Json -InputObject $raw -ErrorAction Stop
    } catch {
        throw "AWS $($Arguments[0]) $($Arguments[1]) returned invalid JSON for $Resource."
    }
}

function Get-PortalClient {
    $result = Invoke-AwsJson -Arguments @('cognito-idp', 'describe-user-pool-client',
        '--user-pool-id', $poolId, '--client-id', $clientId) -Resource "$poolId/$clientId"
    $client = $result.UserPoolClient
    if ($client.UserPoolId -cne $poolId -or $client.ClientId -cne $clientId -or
        $client.ClientName -cne $clientName -or $client.PSObject.Properties['ClientSecret'] -or
        $client.AllowedOAuthFlowsUserPoolClient -ne $true -or
        $client.AllowedOAuthFlows -cnotcontains 'code' -or
        $client.AllowedOAuthScopes -cnotcontains $scope -or
        $client.SupportedIdentityProviders -cnotcontains 'COGNITO' -or
        $client.CallbackURLs -cnotcontains $existingPortal -or
        $client.LogoutURLs -cnotcontains $existingPortal) {
        throw "Cognito client does not match the VortexBird public OAuth client contract for $poolId/$clientId."
    }
    return $client
}

function Get-ClientUpdateSettings {
    param($Client, $UpdateSchema)

    $settings = [ordered]@{}
    $readOnlyProperties = @('CreationDate', 'LastModifiedDate')
    foreach ($name in ($Client.PSObject.Properties.Name | Sort-Object -CaseSensitive)) {
        if ($readOnlyProperties -ccontains $name) { continue }
        if (-not $UpdateSchema.PSObject.Properties[$name]) {
            throw "Cognito app client setting '$name' cannot be safely preserved with this AWS CLI version."
        }
        $settings[$name] = $Client.$name
    }
    return $settings
}

function Get-RailwayPortalUrl {
    param([string]$Value)

    $uri = $null
    if (-not [uri]::TryCreate($Value, [UriKind]::Absolute, [ref]$uri) -or
        $uri.Scheme -cne 'https' -or $uri.Port -ne 443 -or $uri.UserInfo -or
        $uri.AbsolutePath -cne '/' -or $uri.Query -or $uri.Fragment -or
        $uri.Host -cnotmatch '^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.up\.railway\.app$') {
        throw 'Use the root HTTPS URL generated by Railway for the VortexBird frontend.'
    }
    $origin = "https://$($uri.Host)/"
    $previousProgressPreference = $ProgressPreference
    try {
        $ProgressPreference = 'SilentlyContinue'
        $response = Invoke-WebRequest -Uri $origin -UseBasicParsing -MaximumRedirection 0 -TimeoutSec 20
    } catch {
        throw "Railway frontend public HTTPS probe failed at ${origin}: $($_.Exception.Message)"
    } finally {
        $ProgressPreference = $previousProgressPreference
    }
    if ($response.StatusCode -ne 200 -or $response.Content -notmatch '<title>\s*VortexBird[^<]*</title>' -or
        $response.Content -notmatch '<div\s+id="root"') {
        throw "Railway did not return the expected VortexBird portal at $origin."
    }
    return $origin
}

function Assert-RailwayPortalDomain {
    param([string]$Url)

    $railway = (Get-Command $RailwayCli -CommandType Application -ErrorAction Stop).Source
    $arguments = @('domain', 'list', '--service', 'vortexbird-frontend',
        '--environment', $RailwayEnvironment, '--json')
    if ($RailwayProjectId) { $arguments += @('--project', $RailwayProjectId) }
    $previousErrorPreference = $ErrorActionPreference
    try {
        $ErrorActionPreference = 'Continue'
        $output = & $railway @arguments 2>&1
        $exitCode = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $previousErrorPreference
    }
    if ($exitCode -ne 0) {
        throw "Railway CLI could not verify the vortexbird-frontend domains (exit $exitCode)."
    }
    try {
        $domains = (ConvertFrom-Json -InputObject ($output -join [Environment]::NewLine)).domains
    } catch {
        throw 'Railway domain list returned unrecognized output.'
    }
    $hostname = ([uri]$Url).Host
    if (@($domains | Where-Object { $_.domain -ceq $hostname }).Count -ne 1) {
        throw "The Railway project does not list $hostname as a domain of vortexbird-frontend."
    }
}

function Read-BindingManifest {
    $rows = @()
    $subjects = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
    $batch = $null
    foreach ($role in $roles) {
        $response = Invoke-AwsJson -Arguments @('cognito-idp', 'list-users-in-group', '--user-pool-id',
            $poolId, '--group-name', $role) -Resource "$poolId/$role"
        $users = @($response.Users)
        if ($users.Count -ne 1 -or $users[0].Enabled -ne $true -or $users[0].UserStatus -cne 'CONFIRMED') {
            throw "Cognito role $role must contain exactly one enabled, confirmed user."
        }
        $attributes = @{}
        foreach ($attribute in $users[0].Attributes) {
            $attributes[$attribute.Name] = $attribute.Value
        }
        $roleBatch = $attributes['custom:pilot_batch']
        $subject = $attributes['sub']
        $email = $attributes['email']
        if ($roleBatch -cnotmatch '^[a-f0-9]{32}$' -or
            ($null -ne $batch -and $roleBatch -cne $batch) -or
            $attributes['custom:pilot_role'] -cne $role -or $attributes['email_verified'] -cne 'true' -or
            $subject -cnotmatch '^[a-f0-9]{8}-(?:[a-f0-9]{4}-){3}[a-f0-9]{12}$' -or
            $subject -ceq [Guid]::Empty.ToString('D') -or -not $subjects.Add($subject)) {
            throw "Cognito role $role has inconsistent pilot account attributes."
        }
        $roleSlug = $role.ToLowerInvariant().Replace('_', '-')
        if ($email -cne "vb-$roleSlug-$($roleBatch.Substring(0, 8))@pilot.vortexbird.invalid") {
            throw "Cognito role $role does not match the original VortexBird pilot login pattern."
        }
        $batch = $roleBatch
        $rows += [pscustomobject]@{ role = $role; subject = $subject; email = $email }
    }
    return [pscustomobject]@{ batch = $batch; issuer = $issuer; accounts = $rows }
}

if ($Apply -and -not $FrontendUrl) { throw '-Apply requires -FrontendUrl.' }
$railwayPortal = if ($FrontendUrl) { Get-RailwayPortalUrl -Value $FrontendUrl }
$identity = Invoke-AwsJson -Arguments @('sts', 'get-caller-identity') -Resource $account
if ($identity.Account -cne $account) { throw "AWS profile '$Profile' is not in the VortexBird account." }
$domain = Invoke-AwsJson -Arguments @('cognito-idp', 'describe-user-pool-domain',
    '--domain', $domainPrefix) -Resource $domainPrefix
if ($domain.DomainDescription.UserPoolId -cne $poolId -or
    $domain.DomainDescription.AWSAccountId -cne $account -or
    $domain.DomainDescription.Status -cne 'ACTIVE') {
    throw "Cognito hosted login domain does not match the active VortexBird pool $poolId."
}
$client = Get-PortalClient
$manifest = Read-BindingManifest
$changed = $false
$needsUpdate = $railwayPortal -and ($client.CallbackURLs -cnotcontains $railwayPortal -or
    $client.LogoutURLs -cnotcontains $railwayPortal)

if ($Apply -and $needsUpdate -and $PSCmdlet.ShouldProcess("$poolId/$clientId",
        "Append Railway portal callback and logout URL $railwayPortal")) {
    Assert-RailwayPortalDomain -Url $railwayPortal
    $schema = Invoke-AwsJson -Arguments @('cognito-idp', 'update-user-pool-client', '--generate-cli-skeleton', 'input') -Resource 'local AWS CLI input schema'
    $settings = Get-ClientUpdateSettings -Client $client -UpdateSchema $schema
    $current = Get-ClientUpdateSettings -Client (Get-PortalClient) -UpdateSchema $schema
    if (($settings | ConvertTo-Json -Depth 20 -Compress) -cne ($current | ConvertTo-Json -Depth 20 -Compress)) {
        throw 'The Cognito client changed during validation. Run the script again with the current configuration.'
    }
    if ($settings.CallbackURLs -cnotcontains $railwayPortal) { $settings.CallbackURLs = @($settings.CallbackURLs) + $railwayPortal }
    if ($settings.LogoutURLs -cnotcontains $railwayPortal) { $settings.LogoutURLs = @($settings.LogoutURLs) + $railwayPortal }
    $uriFile = [IO.Path]::GetTempFileName()
    try {
        [IO.File]::WriteAllText($uriFile, ($settings | ConvertTo-Json -Depth 20), [Text.UTF8Encoding]::new($false))
        $null = Invoke-AwsJson -Arguments @('cognito-idp', 'update-user-pool-client',
            '--cli-input-json', "file://$uriFile") -Resource "$poolId/$clientId"
    } finally {
        Remove-Item -LiteralPath $uriFile -Force
    }
    $client = Get-PortalClient
    $actual = Get-ClientUpdateSettings -Client $client -UpdateSchema $schema
    if (($settings | ConvertTo-Json -Depth 20 -Compress) -cne ($actual | ConvertTo-Json -Depth 20 -Compress)) {
        throw 'The Cognito client update returned settings that did not match the preserved configuration. Review the client before testing login.'
    }
    $changed = $true
    $needsUpdate = $false
}

$summary = [pscustomobject][ordered]@{
    UserPoolId          = $poolId
    ClientId            = $clientId
    Issuer              = $issuer
    AuthorizationOrigin = $authorizationOrigin
    Scope               = $scope
    CallbackUrls        = @($client.CallbackURLs)
    LogoutUrls          = @($client.LogoutURLs)
    RailwayPortal       = $railwayPortal
    NeedsUpdate         = [bool]$needsUpdate
    Changed             = $changed
    BindingCount        = @($manifest.accounts).Count
}
if ($IncludeBindingManifest) {
    $display = [System.Management.Automation.PSPropertySet]::new('DefaultDisplayPropertySet',
        [string[]]$summary.PSObject.Properties.Name)
    Add-Member -InputObject $summary -MemberType MemberSet -Name PSStandardMembers -Value $display
    Add-Member -InputObject $summary -NotePropertyName BindingManifest -NotePropertyValue $manifest
}
return $summary
